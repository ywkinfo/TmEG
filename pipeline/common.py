def _render_blocks_to_html_standard(
    blocks: list[dict[str, Any]],
    *,
    part_title: str = "",
    chapter_title: str = "",
    section_title: str = "",
) -> str:
    normalized_blocks = normalize_content_blocks(
        blocks,
        part_title=part_title,
        chapter_title=chapter_title,
        section_title=section_title,
    )
    html_blocks: list[str] = []
    synthetic_procedure_html = _render_synthetic_procedure_figure(section_title)
    if synthetic_procedure_html is not None:
        html_blocks.append(synthetic_procedure_html)

    index = 0
    while index < len(normalized_blocks):
        crop_figure_html, next_index = _render_allowlisted_crop_figure(
            normalized_blocks,
            index,
            section_title,
        )
        if crop_figure_html is not None:
            html_blocks.append(crop_figure_html)
            index = next_index
            continue

        multi_column_table_html, next_index = _render_allowlisted_multi_column_table(
            normalized_blocks,
            index,
            section_title,
        )
        if multi_column_table_html is not None:
            html_blocks.append(multi_column_table_html)
            index = next_index
            continue

        comparison_table_html, next_index = _render_allowlisted_comparison_table(
            normalized_blocks,
            index,
            section_title,
        )
        if comparison_table_html is not None:
            html_blocks.append(comparison_table_html)
            index = next_index
            continue

        synthetic_figure_html, next_index = _render_synthetic_timeline_figure(normalized_blocks, index)
        if synthetic_figure_html is not None:
            html_blocks.append(synthetic_figure_html)
            index = next_index
            continue

        block = normalized_blocks[index]
        block_type = block.get("type")
        if block_type == 0:
            block_text = text_block_to_text(block)
            if (
                block_text
                and _looks_like_reader_caption(block_text)
                and index + 1 < len(normalized_blocks)
                and normalized_blocks[index + 1].get("type") == 1
            ):
                figure_html = _render_image_figure(
                    normalized_blocks[index + 1],
                    caption_text=block_text,
                )
                if figure_html is not None:
                    html_blocks.append(figure_html)
                    index += 2
                    continue
            if block_text:
                html_blocks.append(text_to_html(block_text))
            index += 1
            continue

        if block_type != 1:
            index += 1
            continue

        figure_html = _render_image_figure(block)
        if figure_html is not None:
            html_blocks.append(figure_html)
        index += 1

    if not html_blocks:
        return "<p></p>"
    return "\n".join(html_blocks)


def blocks_to_html(
    blocks: list[dict[str, Any]],
    *,
    part_title: str = "",
    chapter_title: str = "",
    section_title: str = "",
) -> str:
    allowlisted_raw_html = _render_allowlisted_raw_section_html(
        blocks,
        part_title=part_title,
        chapter_title=chapter_title,
        section_title=section_title,
    )
    if allowlisted_raw_html is not None:
        return allowlisted_raw_html
    return _render_blocks_to_html_standard(
        blocks,
        part_title=part_title,
        chapter_title=chapter_title,
        section_title=section_title,
    )


def load_page_texts(reader: pymupdf.Document) -> dict[int, str]:
    return {index + 1: extract_page_text(reader.load_page(index)) for index in range(reader.page_count)}


